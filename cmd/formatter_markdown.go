func statusToEmoji(status drips.VerificationStatus) string {
	switch status {
	case drips.StatusVerified:
		return "OK"
	case drips.StatusEscrow:
		return "🔒"
	case drips.StatusUnregistered:
		return "⬜"
	default:
		return "❓"
	}
}
